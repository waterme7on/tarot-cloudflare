import type { CardData, DrawnCard, QuestionType, ReadingSummary, ReportContent, Spread, YesNo } from './schema';

const LIMITATION =
  'Tarot is for reflection and entertainment only. It is not medical, legal, financial or psychological advice, and it cannot predict outcomes.';

const CONTEXT_INTRO: Record<QuestionType, string> = {
  general: 'Read this as a mirror for the situation you have in mind',
  love: 'In a love question, this card speaks to how you connect and what you need',
  career: 'For work, this card points at how you show up and what the next step asks of you',
  money: 'For money, this card describes your relationship with resources right now',
  decision: 'For a decision, this card describes the energy behind the choice rather than a verdict',
};

function contextLine(card: CardData, orientation: 'upright' | 'reversed', q: QuestionType): string {
  if (q === 'love') return card.love[orientation];
  if (q === 'career') return card.career[orientation];
  if (q === 'money') return card.money[orientation];
  return card[orientation].summary;
}

function yesNoFor(card: CardData, orientation: 'upright' | 'reversed'): YesNo {
  if (orientation === 'upright') return card.yesNo;
  if (card.yesNo === 'yes') return 'maybe';
  if (card.yesNo === 'no') return 'maybe';
  return 'no';
}

export function buildFreeSummary(
  drawn: DrawnCard[],
  lookup: (slug: string) => CardData | undefined,
  spread: Spread,
  questionType: QuestionType,
): ReadingSummary {
  const first = drawn[0]!;
  const firstCard = lookup(first.slug)!;
  const firstMeaning = firstCard[first.orientation];

  if (spread === 'one-card') {
    const yn = yesNoFor(firstCard, first.orientation);
    return {
      headline: `${first.name} (${first.orientation})`,
      summary: `${CONTEXT_INTRO[questionType]}: ${contextLine(firstCard, first.orientation, questionType)}`,
      nextAction: firstMeaning.action,
      limitation: LIMITATION,
      yesNo: questionType === 'decision' ? yn : undefined,
    };
  }

  const last = drawn[drawn.length - 1]!;
  const lastCard = lookup(last.slug)!;
  const parts = drawn.map((d) => {
    const c = lookup(d.slug)!;
    return `${d.positionLabel}: ${d.name} ${d.orientation === 'reversed' ? '(reversed)' : ''} — ${contextLine(c, d.orientation, questionType)}`;
  });
  const reversedCount = drawn.filter((d) => d.orientation === 'reversed').length;
  const tone =
    reversedCount === 0
      ? 'All cards are upright, so the energy here is direct and available.'
      : reversedCount === drawn.length
        ? 'Every card is reversed, which usually points at blocked, internal or delayed energy rather than bad news.'
        : `${reversedCount} of ${drawn.length} cards are reversed, so part of this situation is working against the grain.`;
  return {
    headline: `${drawn.map((d) => d.name).join(' · ')}`,
    summary: `${CONTEXT_INTRO[questionType]}. ${tone} ${parts.join(' ')}`,
    nextAction: lastCard[last.orientation].action,
    limitation: LIMITATION,
    yesNo: questionType === 'decision' ? yesNoFor(lastCard, last.orientation) : undefined,
  };
}

export function buildRulesReport(
  drawn: DrawnCard[],
  lookup: (slug: string) => CardData | undefined,
  spread: Spread,
  questionType: QuestionType,
): ReportContent {
  const cards = drawn.map((d) => {
    const c = lookup(d.slug)!;
    const m = c[d.orientation];
    return {
      name: d.name,
      orientation: d.orientation,
      position: d.positionLabel,
      interpretation: [
        `${d.name} ${d.orientation} carries the themes of ${m.keywords.join(', ')}.`,
        m.summary,
        `For a ${questionType} question: ${contextLine(c, d.orientation, questionType)}`,
        `In love: ${c.love[d.orientation]} At work: ${c.career[d.orientation]} With money: ${c.money[d.orientation]}`,
      ].join(' '),
    };
  });
  const free = buildFreeSummary(drawn, lookup, spread, questionType);
  return {
    title: `Your ${spread.replace('-', ' ')} reading`,
    introduction: `This report expands on your free result. ${free.summary}`,
    cards,
    synthesis: free.summary,
    actions: drawn.map((d) => lookup(d.slug)![d.orientation].action),
    reflection:
      'Write down one sentence about what you expected before the draw, and one about what surprised you. The gap between the two is usually where the useful insight sits.',
    disclaimer: `${LIMITATION} This report was generated by our rules engine. Entertainment only.`,
    generator: 'rules',
  };
}

export const ENTERTAINMENT_ONLY_PHRASE = 'entertainment only';
export { LIMITATION };
